// 关键词 → 匹配图片（按关键词命中数排序）
export function searchLocalPool(query, { limit = 24, seed = 0 } = {}) {
  let q = String(query || '').trim().toLowerCase()
  if (!q) return []
  // 去掉常见后缀/语气词，让"环境类""咖啡海报"能命中核心词
  q = q.replace(/[类海报图底素材版式模板宣传主视觉封面配图]/g, '').trim()
  if (!q) return []

  // 同义词/近义词映射，扩大命中
  const SYNONYMS = {
    '环境': ['环保', '自然', '森林', '绿色', '生态'],
    '环保': ['环境', '自然', '森林', '绿色', '生态'],
    '招聘': ['求职', '工作', '面试', '岗位', '商务'],
    '求职': ['招聘', '工作', '面试', '岗位'],
    '美食': ['餐饮', '食物', '料理', '餐厅'],
    '餐饮': ['美食', '食物', '料理', '餐厅'],
    '科技': ['AI', '人工智能', '数码', '电子', '智能'],
    '汽车': ['车', '轿车', '跑车', '驾驶'],
    '旅游': ['旅行', '度假', '风景', '户外'],
    '旅行': ['旅游', '度假', '风景', '户外'],
    '健康': ['医疗', '养生', '保健'],
    '医疗': ['健康', '医生', '医院'],
    '美妆': ['化妆', '护肤', '美容', '彩妆'],
    '婚礼': ['婚庆', '结婚', '浪漫'],
    '婚庆': ['婚礼', '结婚'],
    '房产': ['楼盘', '房屋', '住宅', '房地产'],
    // 情人节 / 爱情主题同义词，命中任意一个即扩大检索范围
    '情人节': ['爱情', '浪漫', '玫瑰', '爱心', '情侣', '恋爱', '表白', '礼物', '红心'],
    '七夕': ['情人节', '爱情', '浪漫', '玫瑰', '爱心', '情侣', '恋爱'],
    '520': ['情人节', '爱情', '浪漫', '玫瑰', '爱心', '情侣'],
    '爱情': ['情人节', '浪漫', '玫瑰', '爱心', '情侣', '恋爱'],
    '浪漫': ['爱情', '玫瑰', '爱心', '情侣', '情人节'],
    '告白': ['表白', '爱情', '浪漫', '情侣', '礼物'],
    '玫瑰': ['爱情', '浪漫', '情人节', '花朵', '红'],
  }
  const expandTerms = new Set([q])
  for (const [k, syns] of Object.entries(SYNONYMS)) {
    if (q.includes(k)) syns.forEach((s) => expandTerms.add(s))
  }

  const scored = POOL.map((img) => {
    let score = 0
    // 命中关键词（含同义词）
    for (const kw of img.keywords) {
      for (const term of expandTerms) {
        if (kw.includes(term) || term.includes(kw)) {
          score += kw.length >= 2 ? 2 : 1
        }
      }
    }
    // 命中分类
    for (const term of expandTerms) {
      if (img.category && (term.includes(img.category) || img.category.includes(term))) score += 3
    }
    // 命中标签
    for (const term of expandTerms) {
      if (img.label && (term.includes(img.label) || img.label.includes(term))) score += 1
    }
    return { img, score }
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score)

  const results = scored.map((x) => x.img)
  // 无命中时不再返回无关的"环保/风景"默认图——那会造成"输入什么都出森林图"的假思考。
  // 改为返回空数组，由上层 asset-search 给出明确提示。
  if (results.length === 0) {
    return []
  }
  return results.slice(0, limit)
}

